// pnpm eval:compare -- eval/results/A.json eval/results/B.json [more…]
// Writes eval/report.md (docs/07 §4): fingerprints, aggregate table (A | B | Δ), per-intent grid, cases where
// configs disagree, the retrieval-only table (eval/results/retrieval-*.json), and the caveats.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";
import { fail } from "./lib/cli.ts";
import { aggregate, type Aggregates, type EvalCase } from "./lib/eval-aggregate.ts";
import { fmtDeltaPp, fmtNum, fmtPct } from "./lib/eval-metrics.ts";

type Case = {
  id: string;
  kind: "in_domain" | "oos";
  gold: string;
  message: string;
  correct: boolean;
  final_intent: string | null;
  refused: boolean;
  refusal_reason: string | null;
  error: string | null;
};
type Result = {
  label: string;
  gateway: string;
  run_at: string;
  fingerprint: Record<string, unknown>;
  aggregates: Aggregates;
  cases: (Case & EvalCase)[];
};

const ROOT = (f: string) => fileURLToPath(new URL(`../${f}`, import.meta.url));
const files = process.argv.slice(2).filter((a) => a !== "--");
if (files.length === 0) fail("usage: pnpm eval:compare -- eval/results/A.json eval/results/B.json");
// Aggregates are recomputed from the per-case records with the current definitions (eval-aggregate.ts).
const results = files.map((f) => {
  const r = JSON.parse(readFileSync(f, "utf-8")) as Omit<Result, "aggregates"> & {
    aggregates: { answer_similarity?: { method?: string } };
  };
  return { ...r, aggregates: aggregate(r.cases, r.aggregates.answer_similarity?.method ?? "") } as Result;
});
const two = results.length === 2;
const [A, B] = results;

const lines: string[] = [];
const out = (s = "") => lines.push(s);
const row = (cells: string[]) => out(`| ${cells.join(" | ")} |`);
const header = (cells: string[]) => {
  row(cells);
  row(cells.map(() => "---"));
};

out("# Evaluation report");
out();
out(
  `Generated by \`pnpm eval:compare\` on ${new Date().toISOString().slice(0, 10)} from ${files.map((f) => `\`${basename(f)}\``).join(", ")}.`,
);
out(
  "End-to-end through the gateway HTTP API (auth, quota, retrieval, routing, streaming, metering), 27 in-domain cases (1 per intent, hard flags preferred) + 5 OOS. No debug overrides.",
);
out();

out("## 1. Configurations (fingerprint from `/healthz`)");
out();
const fp = (r: Result, key: string) => {
  const v = r.fingerprint[key];
  return v === undefined || v === null ? "—" : typeof v === "object" ? JSON.stringify(v) : String(v);
};
const backends = (r: Result) =>
  ((r.fingerprint["backends"] as { id: string; model: string }[] | undefined) ?? [])
    .map((b) => `${b.id} (${b.model})`)
    .join(" → ");
header(["", ...results.map((r) => `**${r.label}**`)]);
row(["profile", ...results.map((r) => fp(r, "profile"))]);
row(["backends (priority)", ...results.map(backends)]);
row(["thinking level", ...results.map((r) => fp(r, "thinking_level"))]);
row(["embedding model", ...results.map((r) => fp(r, "embedding_model"))]);
row(["retrieval mode", ...results.map((r) => fp(r, "retrieval_mode"))]);
row(["prompt", ...results.map((r) => fp(r, "prompt_version"))]);
row(["thresholds", ...results.map((r) => fp(r, "thresholds"))]);
row(["gateway / run at", ...results.map((r) => `${r.gateway} · ${r.run_at.slice(0, 16)}Z`)]);
out();
for (const r of results) {
  const note = (r as Result & { note?: string }).note;
  if (note) out(`> **${r.label}:** ${note}`);
}
out();

out("## 2. Aggregate metrics");
out();
type Metric = [string, (r: Result) => number | null | undefined, "pct" | "num" | "ms" | "usd" | "tok"];
const metrics: Metric[] = [
  ["Intent accuracy (final, refusals = wrong)", (r) => r.aggregates.intent_accuracy, "pct"],
  ["  on answers from a real model (excl. mock)", (r) => r.aggregates.model_answers.intent_accuracy, "pct"],
  ["  kNN-only intent accuracy", (r) => r.aggregates.knn_accuracy, "pct"],
  ["  LLM header accuracy (real-model headers only)", (r) => r.aggregates.llm_header_accuracy, "pct"],
  ["  hard-flag cases (Z/Q/K/W)", (r) => r.aggregates.hard_flag_intent_accuracy, "pct"],
  ["Retrieval hit@1 / gold intent", (r) => r.aggregates.retrieval_hit1, "pct"],
  ["Retrieval hit@5", (r) => r.aggregates.retrieval_hit5, "pct"],
  ["OOS refusal rate (n=5)", (r) => r.aggregates.oos_refusal_rate, "pct"],
  ["In-domain false-refusal rate (n=27)", (r) => r.aggregates.in_domain_false_refusal_rate, "pct"],
  ["Answer similarity to gold (mean cosine)", (r) => r.aggregates.answer_similarity.mean, "num"],
  ["  on answers from a real model (excl. mock)", (r) => r.aggregates.model_answers.answer_similarity_mean, "num"],
  ["TTFT p50 (client)", (r) => r.aggregates.latency_ms["client_ttft_p50"], "ms"],
  ["TTFT p95 (client)", (r) => r.aggregates.latency_ms["client_ttft_p95"], "ms"],
  ["TTFT p50, real model served first try", (r) => r.aggregates.latency_ms["model_ttft_p50"], "ms"],
  ["Total latency p50 (client)", (r) => r.aggregates.latency_ms["client_total_p50"], "ms"],
  ["Total latency p95 (client)", (r) => r.aggregates.latency_ms["client_total_p95"], "ms"],
  ["Mean prompt tokens (per LLM request)", (r) => r.aggregates.tokens_mean.prompt, "tok"],
  ["Mean completion tokens (per LLM request)", (r) => r.aggregates.tokens_mean.completion, "tok"],
  ["Mean thinking tokens (per LLM request)", (r) => r.aggregates.tokens_mean.thinking, "tok"],
  ["Cost per 1,000 requests (list-price equivalent)", (r) => r.aggregates.cost_usd.per_1000_requests, "usd"],
  ["Escalation rate", (r) => r.aggregates.reliability.escalation_rate, "pct"],
  ["Fallback rate", (r) => r.aggregates.reliability.fallback_rate, "pct"],
  ["Error rate", (r) => r.aggregates.reliability.error_rate, "pct"],
];
const fmt = (x: number | null | undefined, kind: Metric[2]) =>
  x === null || x === undefined
    ? "—"
    : kind === "pct"
      ? fmtPct(x)
      : kind === "ms"
        ? `${Math.round(x)} ms`
        : kind === "usd"
          ? `$${x.toFixed(4)}`
          : kind === "tok"
            ? x.toFixed(0)
            : fmtNum(x);
const delta = (a: number | null | undefined, b: number | null | undefined, kind: Metric[2]) => {
  if (a == null || b == null) return "—";
  if (kind === "pct") return fmtDeltaPp(a, b);
  const d = b - a;
  const s = d >= 0 ? "+" : "";
  return kind === "ms"
    ? `${s}${Math.round(d)} ms`
    : kind === "usd"
      ? `${s}$${d.toFixed(4)}`
      : kind === "tok"
        ? `${s}${d.toFixed(0)}`
        : `${s}${d.toFixed(3)}`;
};
header(["Metric", ...results.map((r) => r.label), ...(two ? ["Δ (B − A)"] : [])]);
for (const [name, pick, kind] of metrics) {
  row([name, ...results.map((r) => fmt(pick(r), kind)), ...(two ? [delta(pick(A!), pick(B!), kind)] : [])]);
}
out();
out(
  `Outcomes: ${results.map((r) => `**${r.label}** ${JSON.stringify(r.aggregates.reliability.outcomes)}`).join(" · ")}.`,
);
out(
  `Served by: ${results.map((r) => `**${r.label}** ${JSON.stringify(r.aggregates.served_by)}`).join(" · ")}. The mock answers with the kNN intent and the top-1 KB answer, so the rows marked “excl. mock” isolate the real model.`,
);
out(`Answer similarity: ${A!.aggregates.answer_similarity.method}.`);
out();

out("## 3. Per-intent results (✓ correct, ✗ wrong, R refused, E error)");
out();
const mark = (c: Case | undefined) =>
  !c ? " " : c.error && !c.final_intent && !c.refused ? "E" : c.correct ? "✓" : c.refused ? "R" : "✗";
header(["case", "gold", ...results.map((r) => r.label), "message"]);
for (const c of A!.cases) {
  row([c.id, c.gold, ...results.map((r) => mark(r.cases.find((x) => x.id === c.id))), c.message.replace(/\|/g, "\\|")]);
}
out();

out("## 4. Cases where the configurations disagree");
out();
const differing = A!.cases.filter(
  (c) => new Set(results.map((r) => mark(r.cases.find((x) => x.id === c.id)))).size > 1,
);
if (!two) out("_Only one configuration in this report._");
else if (differing.length === 0) out("_None: both configurations got the same cases right and wrong._");
for (const c of differing) {
  const desc = (r: Result) => {
    const x = r.cases.find((y) => y.id === c.id)!;
    return x.refused ? `refused (${x.refusal_reason})` : (x.final_intent ?? x.error ?? "—");
  };
  out(`- \`${c.id}\` gold **${c.gold}** — “${c.message}”: ${results.map((r) => `${r.label} → ${desc(r)}`).join("; ")}`);
}
out();

out("## 5. Retrieval-only evaluation (no LLM, decides `RETRIEVAL_MODE`)");
out();
const retrievalFiles = existsSync(ROOT("eval/results"))
  ? readdirSync(ROOT("eval/results")).filter((f) => f.startsWith("retrieval-") && f.endsWith(".json"))
  : [];
if (retrievalFiles.length === 0) out("_No retrieval results found (run `pnpm eval:retrieval`)._");
for (const f of retrievalFiles) {
  type Rm = { n: number; hit1: number | null; hit5: number | null; mrr5: number | null; knn_accuracy: number | null };
  type Gm = {
    oos_recall: number | null;
    in_domain_false_gate_rate: number | null;
    n_oos: number;
    n_in_domain: number;
    threshold: number;
  };
  const r = JSON.parse(readFileSync(ROOT(`eval/results/${f}`), "utf-8")) as {
    embedding_model: string;
    sets: { in_domain: number; dev: number; eval: number; oos: number };
    metrics: Record<"dense" | "hybrid" | "lexical", { all: Rm; hard_flags: Rm; confusable: Rm; gate_eval_only: Gm }>;
    decision: { mode: string; hybrid_improves: boolean; hybrid_gate_safe: boolean; rule: string };
  };
  const m = r.metrics;
  out(
    `**${r.embedding_model}**: ${r.sets.in_domain} in-domain queries (dev ${r.sets.dev} + eval ${r.sets.eval}), ${r.sets.oos} OOS; k=5, RRF k=60, depth 20.`,
  );
  out();
  header(["Metric", "dense", "hybrid", "lexical (fallback)", "hybrid − dense"]);
  const rr = (name: string, pick: (x: (typeof m)["dense"]) => number | null) =>
    row([
      name,
      fmtPct(pick(m.dense)),
      fmtPct(pick(m.hybrid)),
      fmtPct(pick(m.lexical)),
      fmtDeltaPp(pick(m.dense), pick(m.hybrid)),
    ]);
  rr("hit@1", (x) => x.all.hit1);
  rr("hit@5", (x) => x.all.hit5);
  rr("MRR@5", (x) => x.all.mrr5);
  rr("kNN intent accuracy", (x) => x.all.knn_accuracy);
  rr(`hit@1, hard flags (n=${m.dense.hard_flags.n})`, (x) => x.hard_flags.hit1);
  rr("kNN accuracy, hard flags", (x) => x.hard_flags.knn_accuracy);
  rr(`kNN accuracy, confusable intents (n=${m.dense.confusable.n})`, (x) => x.confusable.knn_accuracy);
  rr(`OOS gate recall (eval, n=${m.dense.gate_eval_only.n_oos})`, (x) => x.gate_eval_only.oos_recall);
  rr(
    `In-domain false-gate rate (eval, n=${m.dense.gate_eval_only.n_in_domain})`,
    (x) => x.gate_eval_only.in_domain_false_gate_rate,
  );
  out();
  out(
    `Decision rule: ${r.decision.rule}. Result: **${r.decision.mode}** (hybrid improves: ${r.decision.hybrid_improves}, gate unchanged: ${r.decision.hybrid_gate_safe}).`,
  );
  out();
}

out("## 6. Caveats");
out();
out(
  "- **Small n.** 27 in-domain cases: one case = 3.7 pp; 5 OOS cases: one case = 20 pp. Differences of a few points are within noise.",
);
out(
  "- **Paraphrase leakage.** The dataset is paraphrase-heavy; cross-split dedup removes exact normalized duplicates only, so kNN accuracy is optimistic. Hard-flag cases and OOS cases are included to counter this.",
);
out(
  "- **Thresholds** were calibrated on the dev split (98% in-domain recall); eval cases deliberately carry hard flags, so the eval false-refusal rate is expected to be higher than on dev.",
);
out("- **Cost** is a list-price equivalent: the runs used free tiers or a local model.");
out(
  "- **Answer similarity** is a coarse proxy (embedding cosine to one gold answer); the LLM-judge metric was cut (docs/10).",
);
out();

writeFileSync(ROOT("eval/report.md"), lines.join("\n") + "\n");
console.log(`✓ wrote eval/report.md (${results.map((r) => r.label).join(" vs ")})`);
